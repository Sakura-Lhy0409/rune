        · 找到之后**先写一个能稳定复现它的测试**，再修。

        ⚠️ 不要做的：
        · 不要加 `retry` 或 `sleep` 把它压下去 —— 那只是把问题挪到更难查的地方。
        · 不要直接删掉断言。
        """,
        examples: [
            SkillExample(
                title: "典型症状对照",
                content: """
                「单独跑能过、全量跑失败」→ 测试间共享状态。
                「失败时总是少一个元素」→ 断言早于异步完成。
                「换个日期就失败」→ 真实时钟或时区。
                「换个进程就失败、同进程重跑就好」→ 依赖哈希顺序或内存地址。
                """
            )
        ],
        checks: [
            "已用可重复的方式复现（说明复现率与手法）",
            "指出了具体的非确定性来源，而不是「加了个等待就好了」",
            "修复后连续多次运行都稳定",
        ],
        requestedCapabilities: SkillCapabilityRequest(runtimes: [.python, .javascript, .shell])
    )

