    static let sqlMigration = RuneSkill(
        name: "sql-migration",
        description: "写数据库迁移：可回滚、不锁表",
        whenToUse: "改表结构或数据回填",
        body: """
        目标：写一个**能在生产上安全跑、也能回滚**的迁移。

        必须回答的四个问题（写之前先答）：
        1. **锁不锁表**：在大表上加带默认值的列、改列类型、加索引，写法不同锁的粒度完全不同。
