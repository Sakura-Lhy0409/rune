        顺序（扩展-收缩模式）：
        ① 扩展：加新列/新表，允许为空，双写。
        ② 迁移：分批回填，校验两边的数据一致。
        ③ 切换：读走新的。
        ④ 收缩：确认稳定后再删旧的。

        ⚠️ 不要做的：
        · 不要在迁移里跑业务逻辑（那个逻辑以后会变，而迁移必须永远能重放）。
        · 不要在一次迁移里同时改结构和大批量数据。
        · 不要忘了索引：外键列、`WHERE` 里常用的列。
        """,
        checks: [
            "四个问题都有明确答案（尤其「新旧代码并存」与「能否回滚」）",
            "回填是分批的，且有进度可见",
            "迁移能在一个空库上从头跑通",
        ]
    )

